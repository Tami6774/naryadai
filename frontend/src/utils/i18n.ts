/** Правила для сервера-генерируемых строк с числами, например «В очереди 2 нарядов». */
const SERVER_KZ_PATTERNS: Array<[RegExp, (m: RegExpMatchArray) => string]> = [
  [/^Выполняет наряд №(\S+?)( \(пауза\))?(?:, в очереди (\d+))?$/, m =>
    `№${m[1]} нарядты орындауда${m[2] ? ' (үзіліс)' : ''}${m[3] ? `, кезекте ${m[3]}` : ''}`],
  [/^В очереди (\d+) нарядов$/, m => `Кезекте ${m[1]} наряд`],
];

export function translateServer(lang: Lang, text: string | null | undefined): string {
  if (text == null) return '';
  if (lang !== 'kz') return text;
  const exact = SERVER_KZ[text];
  if (exact) return exact;
  for (const [re, fn] of SERVER_KZ_PATTERNS) {
    const m = text.match(re);
    if (m) return fn(m);
  }
  return text;
}
